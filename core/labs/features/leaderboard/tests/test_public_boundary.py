"""Static tests for leaderboard feature layer boundaries and exports."""
import ast
from pathlib import Path

FEATURE_ROOT = Path(__file__).resolve().parents[1]


def _module(path: Path) -> ast.Module:
    return ast.parse(path.read_text(encoding="utf-8-sig"), filename=str(path))


def _exports(path: Path) -> set[str]:
    for node in _module(path).body:
        if isinstance(node, ast.Assign) and any(
            isinstance(target, ast.Name) and target.id == "__all__" for target in node.targets
        ):
            return set(ast.literal_eval(node.value))
    raise AssertionError(f"{path} must declare __all__")


def _imports(path: Path) -> set[str]:
    return {
        node.module
        for node in ast.walk(_module(path))
        if isinstance(node, ast.ImportFrom) and node.module is not None and node.level == 0
    }


def test_public_surface_exports_queries_and_exception():
    exports = _exports(FEATURE_ROOT / "public.py")
    assert "compute_leaderboard_persona" in exports
    assert "compute_leaderboard_lab" in exports
    assert "get_lab_profile" in exports
    assert "get_dashboard_summary" in exports


def test_api_adapters_use_public_and_have_no_direct_model_workflows():
    views = FEATURE_ROOT / "api" / "views.py"
    imports = _imports(views)
    source = views.read_text(encoding="utf-8-sig")
    assert "core.labs.models" not in imports
    assert "LeaderboardPersonaAPIView" in source
    assert "DashboardSummaryAPIView" in source
